"""Invoice PDF generation with fpdf2.

Layout notes that matter for an Indian tax invoice:

* The seller's GSTIN, the place of supply and the supply type (intra/inter) are
  printed, because that is what makes the CGST+SGST vs IGST split auditable.
* Amount in words uses Indian numbering (crore/lakh).
* The currency is written as "Rs." — the ₹ glyph needs a Unicode TTF, and this
  project refuses to depend on a font file being present at runtime. See README.

The renderer takes plain dicts (the same shape the API returns), so it can be
unit-tested and re-used by a worker that emails invoices.
"""

from __future__ import annotations

from datetime import datetime
from io import BytesIO

from fpdf import FPDF

PAGE_W = 210
MARGIN = 12
CONTENT_W = PAGE_W - 2 * MARGIN  # 186 mm


class InvoicePDF(FPDF):
    def __init__(self, *, number: str, tenant_name: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.invoice_number = number
        self.tenant_name = tenant_name
        self.set_margins(MARGIN, MARGIN, MARGIN)
        self.set_auto_page_break(auto=True, margin=20)

    def footer(self):  # called by fpdf2 on every page
        self.set_y(-16)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(120, 120, 120)
        self.cell(0, 5, f"{self.tenant_name} | {self.invoice_number} | e-invoice not applicable "
                        f"(turnover below threshold)", align="L")
        self.ln(4)
        self.cell(0, 5, f"Page {self.page_no()} of {{nb}} | Generated by BillBook", align="L")


def _rupees(value) -> str:
    """Format a number as Indian-grouped rupees, e.g. 1234567.5 → 12,34,567.50."""
    amount = f"{float(value):.2f}"
    whole, _, paise = amount.partition(".")
    sign = "-" if whole.startswith("-") else ""
    whole = whole.lstrip("-")
    if len(whole) > 3:
        head, tail = whole[:-3], whole[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        if head:
            groups.insert(0, head)
        whole = ",".join(groups + [tail])
    return f"{sign}Rs. {whole}.{paise}"


def _clip(text: str, width: int) -> str:
    return text if len(text) <= width else text[: width - 1] + "…"


def render_invoice_pdf(invoice: dict, tenant: dict) -> bytes:
    """Render one invoice and return the PDF bytes."""
    pdf = InvoicePDF(number=invoice["number"], tenant_name=tenant["name"])
    pdf.alias_nb_pages()
    pdf.add_page()

    # ---------------- header ----------------
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(20, 20, 30)
    pdf.cell(0, 8, _clip(tenant["name"], 48), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(90, 90, 100)
    if tenant.get("address"):
        pdf.cell(0, 4, _clip(tenant["address"], 110), new_x="LMARGIN", new_y="NEXT")
    gstin = tenant.get("gstin") or "Unregistered"
    pdf.cell(0, 4, f"GSTIN: {gstin}   |   State code: {tenant['state_code']}",
             new_x="LMARGIN", new_y="NEXT")

    pdf.ln(2)
    pdf.set_draw_color(200, 200, 210)
    pdf.set_text_color(20, 20, 30)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(CONTENT_W / 2, 7, "TAX INVOICE", border="B")
    pdf.set_font("Helvetica", "B", 9)
    pdf.cell(CONTENT_W / 2, 7, invoice["number"], border="B", align="R",
             new_x="LMARGIN", new_y="NEXT")

    # ---------------- meta block ----------------
    pdf.ln(3)
    issued = invoice["issued_at"]
    try:
        issued = datetime.fromisoformat(issued).strftime("%d %b %Y, %H:%M UTC")
    except (TypeError, ValueError):
        pass

    pdf.set_font("Helvetica", "B", 8)
    pdf.cell(24, 5, "Billed to")
    pdf.set_font("Helvetica", "", 9)
    pdf.cell(0, 5, _clip(invoice["customer_name"], 60), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 8)
    pdf.cell(24, 5, "")
    customer_gstin = invoice.get("customer_gstin") or "B2C (unregistered)"
    pdf.cell(0, 5, f"Customer GSTIN: {customer_gstin}", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(24, 5, "")
    pdf.cell(0, 5, f"Issued: {issued}", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(24, 5, "")
    supply = "Intra-state (CGST + SGST)" if invoice["supply_type"] == "intra" else "Inter-state (IGST)"
    pdf.cell(0, 5,
             f"Place of supply: {invoice['place_of_supply']}   |   {supply}   |   "
             f"Status: {invoice['status'].upper()}",
             new_x="LMARGIN", new_y="NEXT")

    # ---------------- line items ----------------
    pdf.ln(4)
    headers = (("#", 8, "L"), ("Description", 62, "L"), ("HSN", 16, "L"), ("Qty", 14, "R"),
               ("Rate", 22, "R"), ("Disc%", 12, "R"), ("Taxable", 24, "R"),
               ("GST%", 12, "R"), ("Amount", 16, "R"))
    pdf.set_font("Helvetica", "B", 7.5)
    pdf.set_fill_color(238, 240, 245)
    for title, width, align in headers:
        pdf.cell(width, 6, title, border=1, align=align, fill=True)
    pdf.ln(6)

    pdf.set_font("Helvetica", "", 7.5)
    for index, line in enumerate(invoice["lines"], start=1):
        if pdf.get_y() > 250:  # keep the table readable across pages
            pdf.add_page()
            pdf.set_font("Helvetica", "B", 7.5)
            for title, width, align in headers:
                pdf.cell(width, 6, title, border=1, align=align, fill=True)
            pdf.ln(6)
            pdf.set_font("Helvetica", "", 7.5)
        pdf.cell(8, 6, str(index), border=1)
        pdf.cell(62, 6, _clip(line["description"], 34), border=1)
        pdf.cell(16, 6, _clip(line.get("hsn") or "-", 8), border=1)
        pdf.cell(14, 6, f"{line['qty']:g}", border=1, align="R")
        pdf.cell(22, 6, _rupees(line["unit_price"]), border=1, align="R")
        pdf.cell(12, 6, f"{line['discount_pct']:g}", border=1, align="R")
        pdf.cell(24, 6, _rupees(line["taxable_value"]), border=1, align="R")
        pdf.cell(12, 6, f"{line['gst_rate']:g}", border=1, align="R")
        pdf.cell(16, 6, _rupees(line["line_total"]), border=1, align="R", new_x="LMARGIN", new_y="NEXT")

    # ---------------- tax summary + totals ----------------
    pdf.ln(4)
    left_w, right_w = 124, 62
    y_start = pdf.get_y()

    pdf.set_font("Helvetica", "B", 7.5)
    pdf.cell(left_w, 5, "Tax summary", new_x="RIGHT", new_y="TOP")
    pdf.cell(right_w, 5, "", align="R", new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 7)
    rate_headers = (("GST%", 14), ("Taxable", 36), ("CGST", 26), ("SGST", 26), ("IGST / Cess", 22))
    x_left = pdf.get_x()
    for title, width in rate_headers:
        pdf.cell(width, 5, title, border="B", align="R" if title != "GST%" else "L")
    pdf.ln(5)
    pdf.set_font("Helvetica", "", 7)
    for row in invoice.get("tax_breakup") or []:
        pdf.cell(14, 5, f"{row['gst_rate']:g}%")
        pdf.cell(36, 5, _rupees(row["taxable_value"]), align="R")
        pdf.cell(26, 5, _rupees(row["cgst"]), align="R")
        pdf.cell(26, 5, _rupees(row["sgst"]), align="R")
        pdf.cell(22, 5, _rupees(row["igst"] + row["cess"]), align="R", new_x="LMARGIN", new_y="NEXT")
    if not invoice.get("tax_breakup"):
        # build the breakup from the header totals when the caller only sent totals
        pdf.cell(14, 5, "—")
        pdf.cell(36, 5, _rupees(invoice["subtotal"]), align="R")
        pdf.cell(26, 5, _rupees(invoice["cgst"]), align="R")
        pdf.cell(26, 5, _rupees(invoice["sgst"]), align="R")
        pdf.cell(22, 5, _rupees(invoice["igst"] + invoice["cess"]), align="R",
                 new_x="LMARGIN", new_y="NEXT")

    # totals block, right column, aligned with the tax summary
    pdf.set_xy(MARGIN + left_w, y_start + 10)
    totals = [
        ("Taxable value", invoice["subtotal"]),
        ("Discount", -invoice.get("discount_total", 0)),
        ("CGST", invoice["cgst"]),
        ("SGST", invoice["sgst"]),
        ("IGST", invoice["igst"]),
        ("Cess", invoice["cess"]),
        ("Round off", invoice["round_off"]),
    ]
    pdf.set_font("Helvetica", "", 7.5)
    for label, value in totals:
        if float(value) == 0 and label in {"IGST", "Cess", "Discount"}:
            continue
        pdf.set_x(MARGIN + left_w)
        pdf.cell(40, 5, label)
        pdf.cell(right_w - 40, 5, _rupees(value), align="R", new_x="LMARGIN", new_y="NEXT")

    pdf.set_x(MARGIN + left_w)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_fill_color(238, 240, 245)
    pdf.cell(40, 7, "Total", border="T", fill=True)
    pdf.cell(right_w - 40, 7, _rupees(invoice["total"]), border="T", align="R", fill=True,
             new_x="LMARGIN", new_y="NEXT")

    # ---------------- words + HSN rollup ----------------
    pdf.ln(5)
    pdf.set_font("Helvetica", "B", 8)
    pdf.cell(0, 5, "Amount in words", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "I", 8)
    pdf.multi_cell(0, 4.5, invoice["amount_in_words"])

    if invoice.get("hsn_summary"):
        pdf.ln(2)
        pdf.set_font("Helvetica", "B", 8)
        pdf.cell(0, 5, "HSN-wise summary", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 7)
        for row in invoice["hsn_summary"]:
            pdf.cell(30, 4, f"HSN {row['hsn']}")
            pdf.cell(30, 4, f"{row['gst_rate']:g}% GST")
            pdf.cell(30, 4, f"Qty {row['qty']:g}")
            pdf.cell(40, 4, f"Taxable {_rupees(row['taxable_value'])}")
            pdf.cell(0, 4, f"Tax {_rupees(row['tax'])}", new_x="LMARGIN", new_y="NEXT")

    if invoice.get("notes"):
        pdf.ln(2)
        pdf.set_font("Helvetica", "", 7.5)
        pdf.multi_cell(0, 4.5, f"Notes: {invoice['notes']}")

    pdf.ln(6)
    pdf.set_font("Helvetica", "", 7)
    pdf.set_text_color(110, 110, 120)
    pdf.multi_cell(
        0, 4,
        "Declaration: we declare that this invoice shows the actual price of the goods/services "
        "described and that all particulars are true and correct. Computer-generated invoice; "
        "no physical signature required. Reverse charge: No. Export/SEZ: not applicable.",
    )
    pdf.set_text_color(20, 20, 30)
    pdf.ln(8)
    pdf.set_font("Helvetica", "B", 8)
    pdf.cell(0, 5, f"For {tenant['name']}", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(8)
    pdf.set_font("Helvetica", "", 8)
    pdf.cell(0, 5, "Authorised signatory", align="R", new_x="LMARGIN", new_y="NEXT")

    output = pdf.output()
    return bytes(output)


def invoice_filename(number: str) -> str:
    """Deterministic download filename: INV/2026-27/0001 → INV-2026-27-0001.pdf"""
    safe = "".join(char if char.isalnum() or char in "-_" else "-" for char in number)
    return f"{safe}.pdf"
